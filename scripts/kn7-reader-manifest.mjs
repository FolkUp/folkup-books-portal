#!/usr/bin/env node
/**
 * kn.7 «Трудности диалога» reader manifest + chapters generator — pre-build step.
 *
 * Source: content/kn7/ru/parts/KN7-*.md (17 separate part files, NOT single MASTER.md).
 * Pattern hybrid kn1 (per-file) + kn5 (HTML strip): reads parts/*.md sorted by KN7-NN prefix,
 * strips HTML comments (approach B per Iskra S311-22 «snyat при сборке manifest»), extracts
 * title from first `# ...` heading, produces:
 *   1. content/kn7/ru/chapters-manifest.json — metadata index (~2 KB)
 *   2. content/kn7/ru/chapters-html/{slug}.js — pre-rendered HTML per section, ES modules
 *      с default export string. Loaded via dynamic import glob per Vite chunk split.
 *
 * Slug scheme (stable across parts edits):
 *   KN7-00-OBLOZHKA-OGLAVLENIE   → title-page (intro, order 5)
 *   KN7-01-VHOD-Rybka            → intro (entry, order 10)
 *   KN7-02-glava-1-1-…           → chapter-1-1 (order 20)
 *   KN7-03-glava-1-2-…           → chapter-1-2 (order 30)
 *   KN7-04-glava-2-1-…           → chapter-2-1 (order 40)
 *   KN7-05-glava-2-2-…           → chapter-2-2 (order 50)
 *   KN7-06-glava-3-1-…           → chapter-3-1 (order 60)
 *   KN7-06a-INTERMEDIYA-Zanzibar → intermezzo-zanzibar (order 65)
 *   KN7-06b-MOST-Lambushka       → bridge-lambushka (order 68)
 *   KN7-07-glava-3-2-…           → chapter-3-2 (order 70)
 *   KN7-08-glava-3-3-…           → chapter-3-3 (order 80)
 *   KN7-09-glava-3-4-…           → chapter-3-4 (order 90)
 *   KN7-10-uroven4-…             → level-4 (order 100)
 *   KN7-11-VYHOD-…               → exit-door (order 110)
 *   KN7-12-prilozhenie-…3        → apparatus-level-3 (order 800, apparatus)
 *   KN7-13-prilozhenie-…4        → apparatus-level-4 (order 810, apparatus)
 *   KN7-14-prilozhenie-filosofiya → apparatus-philosophy (order 820, apparatus)
 *   KN7-15-KOLOFON (когда Kочегар добавит) → colophon (order 900, apparatus)
 *   KN7-16-UKAZATEL               → apparatus-index (order 910, apparatus)
 *
 * Origin: Iskra S312-01 §2 mandate «DEPLOY-VSYO-GOTOVOE»: kn7 читалка ships FIRST (не ждёт
 * Kочегарова свода) через manifest по частям parts/. S1ORCH cont+1 dispatched к S1DEFIX cont+7
 * batch 2 UNBLOCK 2026-09-01.
 *
 * precommit:allow-ai-mentions
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve, dirname, join } from 'node:path'
import { marked } from 'marked'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const PROJECT_ROOT = resolve(__dirname, '..')
const PARTS_DIR = resolve(PROJECT_ROOT, 'content/kn7/ru/parts')
const MANIFEST_PATH = resolve(PROJECT_ROOT, 'content/kn7/ru/chapters-manifest.json')
const BODIES_DIR = resolve(PROJECT_ROOT, 'content/kn7/ru/chapters-html')

marked.setOptions({ async: false })
marked.use({ gfm: true })

/**
 * Strip HTML comments <!-- ... --> from markdown. Per Iskra S311-22 mandate approach B
 * (snyat при сборке). Multi-line comments supported. Applied BEFORE marked rendering to keep
 * output clean of ЧАСТЬ N из 14 / md5 / ГРУППА / ВЕРСИЯ metadata that should not reach reader.
 */
function stripHtmlComments(md) {
  return md.replace(/<!--[\s\S]*?-->\s*\n?/g, '')
}

/** Strip leading H1 heading (# ...) — title renders via useHead + h1 в template. */
function stripLeadingH1(md) {
  return md.replace(/^# [^\n]+\n+/, '')
}

/** Extract title from first `# ...` heading. Return null if not found. */
function extractTitle(md) {
  const match = md.match(/^# (.+)$/m)
  return match ? match[1].trim() : null
}

/** Render markdown body к HTML via marked (sync). Strips HTML comments + leading H1. */
function renderBody(rawMarkdown) {
  return marked.parse(stripLeadingH1(stripHtmlComments(rawMarkdown)))
}

/**
 * Serialize HTML string к safe ES module. precommit:allow-ai-mentions marker для index safety.
 * Uses JSON.stringify для escape всех спецсимволов.
 */
function serializeHtmlModule(html) {
  return `// Auto-generated by scripts/kn7-reader-manifest.mjs — DO NOT EDIT.
// Pre-rendered HTML body для kn7 chapter. Loaded via dynamic import per-chunk.
// precommit:allow-ai-mentions
export default ${JSON.stringify(html)}
`
}

/**
 * Map filename prefix (KN7-NN-...) к canonical slug + order + isApparatus flag.
 * Order values chosen для preserve TOC sequence: 5-110 main flow, 800+ apparatus.
 */
function classifyFile(filename) {
  // Sub-parts KN7-06a / KN7-06b BEFORE KN7-06 numeric prefix для sort-key derivation
  if (filename.startsWith('KN7-00-')) return { slug: 'title-page', order: 5, isApparatus: false }
  if (filename.startsWith('KN7-01-')) return { slug: 'intro', order: 10, isApparatus: false }
  if (filename.startsWith('KN7-02-')) return { slug: 'chapter-1-1', order: 20, isApparatus: false }
  if (filename.startsWith('KN7-03-')) return { slug: 'chapter-1-2', order: 30, isApparatus: false }
  if (filename.startsWith('KN7-04-')) return { slug: 'chapter-2-1', order: 40, isApparatus: false }
  if (filename.startsWith('KN7-05-')) return { slug: 'chapter-2-2', order: 50, isApparatus: false }
  if (filename.startsWith('KN7-06-')) return { slug: 'chapter-3-1', order: 60, isApparatus: false }
  if (filename.startsWith('KN7-06a-')) return { slug: 'intermezzo-zanzibar', order: 65, isApparatus: false }
  if (filename.startsWith('KN7-06b-')) return { slug: 'bridge-lambushka', order: 68, isApparatus: false }
  if (filename.startsWith('KN7-07-')) return { slug: 'chapter-3-2', order: 70, isApparatus: false }
  if (filename.startsWith('KN7-08-')) return { slug: 'chapter-3-3', order: 80, isApparatus: false }
  if (filename.startsWith('KN7-09-')) return { slug: 'chapter-3-4', order: 90, isApparatus: false }
  if (filename.startsWith('KN7-10-')) return { slug: 'level-4', order: 100, isApparatus: false }
  if (filename.startsWith('KN7-11-')) return { slug: 'exit-door', order: 110, isApparatus: false }
  if (filename.startsWith('KN7-12-')) return { slug: 'apparatus-level-3', order: 800, isApparatus: true }
  if (filename.startsWith('KN7-13-')) return { slug: 'apparatus-level-4', order: 810, isApparatus: true }
  if (filename.startsWith('KN7-14-')) return { slug: 'apparatus-philosophy', order: 820, isApparatus: true }
  if (filename.startsWith('KN7-15-')) return { slug: 'colophon', order: 900, isApparatus: true }
  if (filename.startsWith('KN7-16-')) return { slug: 'apparatus-index', order: 910, isApparatus: true }
  console.warn(`[kn7-reader-manifest] Unknown filename pattern: ${filename}`)
  return null
}

function main() {
  console.log('[kn7-reader-manifest] Reading parts from', PARTS_DIR)

  if (!existsSync(PARTS_DIR)) {
    console.log(`[kn7-reader-manifest] Parts dir ${PARTS_DIR} does not exist — skipping.`)
    return
  }

  // Read all parts, filter to KN7-*.md (exclude README-*)
  const allFiles = readdirSync(PARTS_DIR)
  const partFiles = allFiles.filter((f) => /^KN7-\d/.test(f) && f.endsWith('.md'))

  const entries = []
  const bodies = {}

  for (const filename of partFiles) {
    const cls = classifyFile(filename)
    if (!cls) continue

    const filePath = join(PARTS_DIR, filename)
    const raw = readFileSync(filePath, 'utf-8')
    const strippedForTitle = stripHtmlComments(raw)
    const title = extractTitle(strippedForTitle) || filename
    const html = renderBody(raw)

    entries.push({
      slug: cls.slug,
      title,
      description: null,
      order: cls.order,
      isApparatus: cls.isApparatus,
    })
    bodies[cls.slug] = html
  }

  entries.sort((a, b) => a.order - b.order)

  const manifest = {
    generated: new Date().toISOString(),
    book: 'kn7',
    locale: 'ru',
    entries,
  }

  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2), 'utf-8')
  console.log(`[kn7-reader-manifest] Wrote ${MANIFEST_PATH} (${entries.length} entries)`)

  // Per-chapter HTML modules — clean-write directory (deleted entries drop out).
  if (existsSync(BODIES_DIR)) rmSync(BODIES_DIR, { recursive: true, force: true })
  mkdirSync(BODIES_DIR, { recursive: true })

  let totalSize = 0
  let maxSize = 0
  let maxSlug = ''
  for (const [slug, html] of Object.entries(bodies)) {
    const modulePath = resolve(BODIES_DIR, `${slug}.js`)
    const content = serializeHtmlModule(html)
    writeFileSync(modulePath, content, 'utf-8')
    const size = Buffer.byteLength(content, 'utf-8')
    totalSize += size
    if (size > maxSize) {
      maxSize = size
      maxSlug = slug
    }
  }

  console.log(
    `[kn7-reader-manifest] Wrote ${Object.keys(bodies).length} chapter HTML modules to ${BODIES_DIR}`,
  )
  console.log(
    `[kn7-reader-manifest]   total: ${(totalSize / 1024).toFixed(1)} KB, max: ${(maxSize / 1024).toFixed(1)} KB (${maxSlug})`,
  )
}

main()
